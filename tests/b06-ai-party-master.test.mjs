const vault=()=>emptyVault();
const runtime=v=>createAiToolRuntime(v,{assistantRuntime:{scope:'business',workspaceId:v.appSettings.activeWorkspaceId||'default',branchId:'main',entity:null}});
const input='Create customer: Coastal Trade LLC; phone: +905392411642; email: sales@coastal.example; city: Istanbul; country: Turkey';
test('B06: explicit English and Arabic party commands parse into exact locally sourced values',()=>{
  assert.deepEqual(parseAiPartyMasterIntent(input),{party:'customer',mode:'create',name:'Coastal Trade LLC',fields:{phone:'+905392411642',email:'sales@coastal.example',city:'Istanbul',country:'Turkey'}});
  assert.deepEqual(parseAiPartyMasterIntent('أضف عميل: شركة اليسر؛ الهاتف: +905392411642؛ البريد: sales@example.com'),{party:'customer',mode:'create',name:'شركة اليسر',fields:{phone:'+905392411642',email:'sales@example.com'}});
  assert.deepEqual(parseAiPartyMasterIntent('عدّل مورد: Turkish Foods؛ المدينة: Istanbul'),{party:'supplier',mode:'update',name:'Turkish Foods',fields:{city:'Istanbul'}});
  assert.equal(parseAiPartyMasterIntent('List all customers'),null);
  assert.equal(parseAiPartyMasterIntent('Do not create customer: Coastal Trade LLC; phone: +905392411642'),null);
  assert.equal(parseAiPartyMasterIntent('لا تسجل عميل: شركة اليسر؛ الهاتف: +905392411642'),null);
  assert.equal(parseAiPartyMasterIntent('Create customer: Coastal Trade LLC'),null);
});
test('B06: customer create is one deterministic, reviewable tool approval, never an implicit save',()=>{
  const v=vault(),before=JSON.stringify(v),plan=deterministicAiToolPlan(input,runtime(v));
  assert.equal(plan?.calls[0].tool,'customer.master');
  const output=executeAiToolPlan(runtime(v),plan);
  assert.equal(output.proposal?.tool,'customer.master');
  assert.equal(output.proposal?.args.mode,'create');
  assert.equal(output.proposal.preview.length,1);
  assert.equal(output.proposal.preview[0].after.phone,'+905392411642');
  assert.equal(output.proposal.preview[0].after.email,'sales@coastal.example');
  assert.equal(JSON.stringify(v),before);
  const after=applyAiPartyMaster(v,output.proposal.args);
  assert.equal(after.customers.length,1);
  assert.equal(after.customers[0].companyNameEn,'Coastal Trade LLC');
  assert.equal(after.customers[0].phone,'+905392411642');
  assert.equal(after.customers[0].email,'sales@coastal.example');
  assert.equal(after.customers[0].paymentDueDays,'');
  assert.equal(after.customers[0].paymentTerms,'');
  assert.equal(v.customers.length,0);
});
