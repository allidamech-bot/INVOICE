test('B06: supplier create and exact existing-name update preserve unrelated fields and company',()=>{
  const v=vault();
  const create=prepareAiPartyMaster(v,parseAiPartyMasterIntent('Create supplier: Turkish Foods; email: office@turkish.example; phone: +905390001122'));
  const created=applyAiPartyMaster(v,create);
  assert.equal(created.suppliers.length,1);
  assert.equal(created.suppliers[0].nameEn,'Turkish Foods');
  assert.equal(created.suppliers[0].address,'');
  const update=prepareAiPartyMaster(created,parseAiPartyMasterIntent('Update supplier: Turkish Foods; city: Istanbul; payment terms: Net 30'));
  assert.equal(update.mode,'update');
  assert.equal(update.preview.before.city,'');
  assert.equal(update.preview.after.city,'Istanbul');
  const next=applyAiPartyMaster(created,update);
  assert.equal(next.suppliers[0].city,'Istanbul');
  assert.equal(next.suppliers[0].paymentTerms,'Net 30');
  assert.equal(next.suppliers[0].email,'office@turkish.example');
  assert.equal(created.suppliers[0].city,'');
});
test('B06: save is atomic and checked after one explicit click',async()=>{
  let current=vault(),calls=0;
  registerVaultMutationBridge(async mutation=>{calls++;current=mutation(current);return current;});
  const staged=prepareAiPartyMaster(current,parseAiPartyMasterIntent('Add supplier: Oasis FMCG; email: partner@oasis.example'));
  const applied=await applyApprovedToolExecution({capability:'tool.execute',tool:'supplier.master',args:staged,label:'Review supplier',rationale:'User approved'});
  assert.equal(calls,1);
  assert.equal(current.suppliers.length,1);
  assert.equal(current.suppliers[0].id,applied.id);
  assert.match(applied.summary,/created after explicit approval/);
});
test('B06: duplicate email or name, unsupported fields, invalid email and forged fields fail closed',()=>{
  let v=vault();
  const first=prepareAiPartyMaster(v,parseAiPartyMasterIntent(input));
  v=applyAiPartyMaster(v,first);
  assert.throws(()=>prepareAiPartyMaster(v,parseAiPartyMasterIntent('Add customer: Coastal Trade LLC; phone: +905000000111')),/already exists/);
  assert.throws(()=>prepareAiPartyMaster(v,parseAiPartyMasterIntent('Add customer: Rival LLC; email: sales@coastal.example')),/Duplicate/);
  assert.throws(()=>parseAiPartyMasterIntent('Add customer: Rival LLC; bank account: IBAN123'),/Unsupported contact field/);
  assert.throws(()=>parseAiPartyMasterIntent('Add customer: Rival LLC; email: wrong-email'),/Invalid contact email/);
  assert.throws(()=>parseAiPartyMasterIntent('Add customer: Rival LLC; phone: 12'),/Invalid contact phone/);
  assert.throws(()=>parseAiPartyMasterIntent('Add customer: Rival LLC; city: Paris; city: London'),/Repeated contact field/);
  const staged=prepareAiPartyMaster(v,parseAiPartyMasterIntent('Add customer: Rival LLC; city: Paris'));
  staged.after.creditLimit='99999';
  assert.throws(()=>applyAiPartyMaster(v,staged),/Unapproved party field/);
  assert.equal(v.customers.length,1);
});
test('B06: stale, ambiguous, company changes and multi-action plans cannot accidentally save',()=>{
  const v=vault(),created=applyAiPartyMaster(v,prepareAiPartyMaster(v,parseAiPartyMasterIntent(input)));
  const intent=parseAiPartyMasterIntent('Update customer: Coastal Trade LLC; city: Ankara');
  const update=prepareAiPartyMaster(created,intent);
  const changed=structuredClone(created);
  changed.customers[0].updatedAt='2026-10-09T00:00:00Z';
  assert.throws(()=>applyAiPartyMaster(changed,update),/changed since preview/);
  const other=structuredClone(created);other.appSettings.activeWorkspaceId='other';
  assert.throws(()=>applyAiPartyMaster(other,update),/Active company changed/);
  assert.throws(()=>prepareAiPartyMaster(other,intent),/No exact customer/);
  const plan=deterministicAiToolPlan(input,runtime(v));
  const mixed=executeAiToolPlan(runtime(v),{...plan,calls:[...plan.calls,{id:'extra',tool:'task.create',args:{title:'second write'},reason:'second write'}]});
  assert.equal(mixed.proposal,null);
  assert.equal(v.customers.length,0);
});
